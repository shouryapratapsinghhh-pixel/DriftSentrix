"""Inject a results section into README.md, generated FROM
reports/results.csv, reports/pa_inflation.csv, and reports/latency.json
-- between the <!-- RESULTS:START --> / <!-- RESULTS:END --> markers.

No number in this section is hand-typed; every one is read from a file
this repo's own scripts produced. Re-run after any experiment/benchmark
change:

    python -m anomaly.experiment --config configs/full_benchmark.yaml
    python -m anomaly.report
    python -m anomaly.scripts.pa_inflation_study --config configs/full_benchmark.yaml
    python scripts/bench_latency.py --model lstm_ae
    python scripts/build_readme_results.py
"""

from __future__ import annotations

import json
import os

import pandas as pd

START_MARKER = "<!-- RESULTS:START -->"
END_MARKER = "<!-- RESULTS:END -->"


def build_section() -> str:
    lines = ["<!-- RESULTS:START -->", "*Generated by `scripts/build_readme_results.py` -- every number below is read from a file, never hand-typed.*", ""]

    if os.path.exists("reports/results.csv"):
        df = pd.read_csv("reports/results.csv")
        oracle = df[df["threshold_mode"] == "oracle"][
            ["model", "point_f1", "pa_f1", "event_f1"]
        ].sort_values("event_f1", ascending=False)
        lines.append("### Point-F1 vs PA-F1 vs Event-F1 (oracle threshold, mean across seeds)\n")
        lines.append(oracle.to_markdown(index=False, floatfmt=".3f"))
        lines.append("")

        deployable = df[df["threshold_mode"].str.startswith("train_percentile")][
            ["model", "point_f1", "pa_f1", "event_f1", "false_alarms_per_1000"]
        ].sort_values("event_f1", ascending=False)
        lines.append("### Same models, deployable threshold (train_percentile, no test labels used)\n")
        lines.append(deployable.to_markdown(index=False, floatfmt=".3f"))
        lines.append("")

    if os.path.exists("reports/pa_inflation.csv"):
        pa_df = pd.read_csv("reports/pa_inflation.csv")
        real = pa_df[pa_df["model"] != "random"]
        mean_point = real["random_point_f1"].mean()
        mean_pa = real["random_pa_f1"].mean()
        lines.append("### PA-inflation study\n")
        lines.append(
            f"A pure-random detector, flagging points at the same rate as each real detector "
            f"above, scores a mean point-F1 of **{mean_point:.3f}** but a mean PA-F1 of "
            f"**{mean_pa:.3f}** -- a **{mean_pa / mean_point:.1f}x inflation** from the metric "
            f"alone, with zero actual detection ability behind it. See "
            f"`reports/figures/pa_inflation.png` and `reports/pa_inflation.csv` for the full "
            f"per-model breakdown.\n"
        )

    for model_name, label in [("lstm_ae", "LSTM-AE"), ("transformer_ae", "Transformer-AE")]:
        path = f"reports/latency_{model_name}.json"
        if os.path.exists(path):
            with open(path) as f:
                lat = json.load(f)
            lines.append(
                f"### {label} streaming latency ({lat['mode']}, n={lat['n_pushes']})\n"
                f"p50 **{lat['p50_ms']:.2f} ms**, p95 **{lat['p95_ms']:.2f} ms**, "
                f"p99 **{lat['p99_ms']:.2f} ms** -- throughput "
                f"**{lat['throughput_points_per_s']:.0f} points/s**.\n"
            )

    lines.append(END_MARKER)
    return "\n".join(lines)


def main() -> None:
    readme_path = "README.md"
    with open(readme_path) as f:
        content = f.read()

    section = build_section()

    if START_MARKER in content and END_MARKER in content:
        start = content.index(START_MARKER)
        end = content.index(END_MARKER) + len(END_MARKER)
        content = content[:start] + section + content[end:]
    else:
        content += f"\n\n{section}\n"

    with open(readme_path, "w") as f:
        f.write(content)
    print(f"updated {readme_path} between {START_MARKER} / {END_MARKER}")


if __name__ == "__main__":
    main()
